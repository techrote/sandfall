// Density exchange is directional and opt-in. A falling material may displace
// a lighter movable material below it; a rising material may displace a
// heavier movable material above it. Keeping this separate from MaterialState
// lets future foams, trapped gases, gels, and pastes decline the exchange even
// when their broad phase would normally suggest it.
enum class DensityMotion : std::uint8_t {
    None,
    Down,
    Up,
};

// FreeMass is the conserved fixed-point Water solver. CellularYield retains
// the intentionally heap-capable, whole-cell movement family used by viscous
// liquids and available to future slush/paste materials.
enum class LateralFlowMode : std::uint8_t {
    None,
    FreeMass,
    CellularYield,
};

struct MaterialDefinition {
    std::string_view name;
    MaterialState state;
    std::uint16_t density;
    std::array<std::uint8_t, 4> rgba;
    bool movable;
    bool valid;
    bool current_rule_available;
    RuleKernel kernel;
    std::uint8_t initial_state_a;
    std::uint8_t initial_state_b;
    std::uint8_t maximum_write_radius;
    DensityMotion density_motion;
    bool accepts_density_exchange;
    LateralFlowMode lateral_flow;
    // Dimensionless gameplay viscosity. Zero is maximally mobile and 255 is
    // the slowest supported liquid. LateralFlowMode::None makes it irrelevant.
    std::uint8_t viscosity_index;
};

