#!/usr/bin/env python3
"""Generate the native liquid-policy catalogue header and contract-vector include.

LCB-001 #200 foundation. The native build embeds the Gate C identity digests and
the reviewed capability matrix as constants, and the native tests replay the
oracle's registered wire vectors. Both files are generated from checked-in
sources only; `--check` fails when either is stale (run in Documentation CI).

    python tools/lcb/native_policy_artifacts.py          # rewrite both files
    python tools/lcb/native_policy_artifacts.py --check  # fail if stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import policy_contract as pc

ROOT = pc.ROOT
HEADER = ROOT / "native/include/cybersand/liquid_policy_catalogue.hpp"
VECTORS_INC = ROOT / "native/tests/liquid_policy_vectors.inc"
STATUS = {"rejected": "Rejected", "current_default": "CurrentDefault",
          "proposed_experimental": "ProposedExperimental", "proposed_alternate": "ProposedAlternate"}
BANNER = ("// GENERATED by tools/lcb/native_policy_artifacts.py. Do not edit; rerun the tool.\n"
          "// Sources: {sources}.\n")


def _bytes(hexdigest: str) -> str:
    raw = bytes.fromhex(hexdigest)
    return ", ".join(f"0x{b:02x}" for b in raw)


def _string(text: str) -> str:
    return json.dumps(text, ensure_ascii=True)


def render_header(matrix_bytes: bytes, catalogue: str) -> str:
    matrix = json.loads(matrix_bytes)
    rows = []
    for row in matrix["liquid_rows"]:
        statuses, masks = [], []
        for family in pc.FAMILIES:
            cell = row["families"][family]
            statuses.append("CellStatus::" + STATUS[cell["status"]])
            masks.append(str(sum(1 << pc.VARIANTS[v] for v in cell["variants"])))
        rows.append(f"    {{{row['material_id']}, {pc.FAMILIES[row['current_default_family']]}, "
                    f"{_string(row['name'])},\n     {{{{{', '.join(statuses)}}}}},\n"
                    f"     {{{{{', '.join(masks)}}}}}}},")
    return (BANNER.format(sources="native/include/cybersand/material.hpp, "
                          "native/include/cybersand/interaction_rules.hpp, "
                          "docs/reference/liquid-solver-capability-matrix.json") + f"""#pragma once

#include <array>
#include <cstdint>

// Identity of the reviewed LCB-000 Gate C material catalogue and capability
// matrix this binary was built from. The digests are the policy wire identity;
// a request naming different digests is refused as stale_capability_matrix.
namespace cybersand::liquid_policy_catalogue {{

enum class CellStatus : std::uint8_t {{
    Rejected = 0,
    CurrentDefault = 1,
    ProposedExperimental = 2,
    ProposedAlternate = 3,
}};

struct LiquidRow {{
    std::uint16_t material_id;
    std::uint8_t default_family;              // wire family code
    const char* name;                         // matrix descriptor name
    std::array<CellStatus, 4> status;         // indexed by family code - 1
    std::array<std::uint8_t, 4> variant_mask; // bit = wire variant code
}};

inline constexpr std::array<std::uint8_t, 32> kCatalogueDigest{{
    {_bytes(catalogue)}}};
inline constexpr std::array<std::uint8_t, 32> kCapabilityMatrixDigest{{
    {_bytes(pc.capability_matrix_digest(matrix_bytes))}}};
inline constexpr std::uint16_t kMaterialDescriptorCount = {matrix["material_descriptor_count"]};
inline constexpr std::array<LiquidRow, {len(rows)}> kLiquidRows{{{{
{chr(10).join(rows)}
}}}};

}}  // namespace cybersand::liquid_policy_catalogue
""")


def _words(words: list[int]) -> str:
    # 64-bit literals so the out-of-int32 transport vector is representable.
    return "{" + ", ".join(f"{w}LL" for w in words) + "}"


def render_vectors(vectors_text: str) -> str:
    data = json.loads(vectors_text)
    builds = []
    for name, build in data["vector_builds"].items():
        qualified = build["qualified_cells"]
        cells = "" if qualified == "all_selectable" else ", ".join(
            f"{{{m}, {pc.FAMILIES[f]}}}" for m, f in qualified)
        builds.append(f"    {{{_string(name)}, {_string(build['catalogue_digest'])}, "
                      f"{_string(build['capability_matrix_digest'])},\n"
                      f"     {sum(1 << (pc.FAMILIES[f] - 1) for f in build['available_families'])}, "
                      f"{'true' if build['native'] else 'false'}, "
                      f"{'false' if qualified == 'all_selectable' else 'true'}, {{{cells}}}}},")
    schemas = []
    for key, schema in data["constants"]["illustrative_block_schemas"].items():
        kind, owner, version = key.split(":")
        fields = ", ".join(f"{{{_string(f[0])}, {f[1]}, {f[2]}}}" for f in schema["fields"])
        schemas.append(f"    {{{'true' if kind == 'family' else 'false'}, {owner}, {version[1:]}, "
                       f"{'true' if schema['mandatory'] else 'false'}, {schema['requires_family'] or 0}, "
                       f"{{{fields}}}}},")
    cases = []
    for case in data["cases"]:
        out = case["outcome"]
        if out["accepted"]:
            tail = (f"true, \"\", -1, \"\", {_string(out['policy_hash'])}, "
                    f"{_string(out['canonical_bytes_hex'])},\n     {_words(out['normalized_envelope'])}")
        else:
            material = -1 if out["material"] is None else out["material"]
            tail = f"false, {_string(out['code'])}, {material}, {_string(out['detail'])}, \"\", \"\", {{}}"
        cases.append(f"    {{{_string(case['name'])}, {_string(case['build'])},\n"
                     f"     {_words(case['words'])},\n     {tail}}},")
    steps = []
    vector_words = {c["name"]: c["words"] for c in data["cases"]}
    for step in data["session_transcript"]:
        label = step["step"]
        words = [] if label == "construct default" else vector_words[label.removeprefix("apply ")]
        accepted = step.get("accepted", True)
        code = "" if step.get("refusal") is None else step["refusal"]["code"]
        steps.append(f"    {{{_string(label)}, {_words(words)}, {'true' if accepted else 'false'}, "
                     f"{_string(code)}, {_string(step['readback_hash'])}, {step['generation']}}},")
    return (BANNER.format(sources="docs/reference/liquid-policy-wire-vectors.json") + f"""// Included only by native/tests/test_liquid_solver_policy.cpp.

inline constexpr std::string_view kVectorCurrentCatalogueDigest =
    {_string(data["current_build_identity"]["catalogue_digest"])};
inline constexpr std::string_view kVectorCurrentCapabilityDigest =
    {_string(data["current_build_identity"]["capability_matrix_digest"])};

inline const std::vector<VectorBuild> kVectorBuilds{{
{chr(10).join(builds)}
}};

inline const std::vector<VectorSchema> kVectorSchemas{{
{chr(10).join(schemas)}
}};

inline const std::vector<VectorCase> kVectorCases{{
{chr(10).join(cases)}
}};

inline const std::vector<VectorSessionStep> kVectorSession{{
{chr(10).join(steps)}
}};
""")


def outputs() -> dict[Path, str]:
    matrix_bytes = pc.MATRIX.read_bytes()
    return {HEADER: render_header(matrix_bytes, pc.catalogue_digest()),
            VECTORS_INC: render_vectors(pc.VECTORS.read_text(encoding="utf-8"))}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        current = path.read_bytes().replace(b"\r\n", b"\n").decode("utf-8") if path.exists() else None
        if args.check:
            if current != text:
                stale.append(str(path.relative_to(ROOT)))
        elif current != text:
            path.write_bytes(text.encode("utf-8"))
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale: " + ", ".join(stale) + "; run python tools/lcb/native_policy_artifacts.py", file=sys.stderr)
        return 1
    if args.check:
        print("native liquid-policy artifacts match their sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
