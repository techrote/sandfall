#!/usr/bin/env python3
"""Native IN optional family-block-v2 contract; historical v1 vectors stay intact."""
from __future__ import annotations
import argparse
import hashlib
import json
import struct
from pathlib import Path
import policy_contract as pc

ROOT = Path(__file__).resolve().parents[2]
JSON_PATH = ROOT / "docs/reference/inertial-parameter-vectors.json"
HEADER_PATH = ROOT / "native/tests/inertial_parameter_vectors.inc"
ADAPTER_PATH = ROOT / "godot/tests/fixtures/lcb/inertial-adapter-parameters.json"
SCHEMAS = {("family", 4, 2): {"fields": (("damping_numerator", 0, 16),), "mandatory": False}}


def identity(numerator: int = 1) -> str:
    if not 0 <= numerator <= 16:
        raise ValueError("damping numerator outside 0..16")
    values = (16, 16, 8, 8, 16, 4, 32, 1, 8, 3, 4, numerator, 16, 1, 4, 1, 3)
    return hashlib.sha256(b"cybersand-inertial-update-v1-state-v1-identity-v1" +
                          struct.pack("<17i", *values)).hexdigest()


def build():
    matrix = pc.MATRIX.read_bytes()
    return pc.make_build(matrix, pc.catalogue_digest(), available=(1, 2, 3, 4),
                         qualified=pc.current_default_cells(matrix) | {(3, 3), (3, 2), (3, 4), (24, 4)},
                         schemas=SCHEMAS)


def vectors():
    native = build()
    assignments = [(m, 4 if m == 24 else f, v) for m, f, v in pc.default_assignments(native)]
    cases = []
    specs = [("omitted-default", [], True)]
    specs += [(f"damping-{n}", [(4, 2, [n])], True) for n in (0, 1, 7, 16)]
    specs += [("below-range", [(4, 2, [-1])], True), ("above-range", [(4, 2, [17])], True),
              ("historical-illustrative-v1", [(4, 1, [4096, 1024])], True),
              ("unknown-v3", [(4, 3, [1])], True), ("missing-word", [(4, 2, [])], True),
              ("extra-word", [(4, 2, [1, 16])], True), ("unused-family", [(4, 2, [1])], False)]
    for name, blocks, use_in in specs:
        request = pc.encode(pc.policy_for(native, assignments if use_in else pc.default_assignments(native), blocks))
        item = {"name": name, "words": request}
        try:
            applied = pc.decode(request, native)
            damping = 1 if not applied["family_blocks"] else applied["family_blocks"][0][2][0]
            item.update(accepted=True, refusal="", damping_numerator=damping,
                        policy_hash=pc.policy_hash(applied), extension_identity=identity(damping))
        except pc.Refusal as refusal:
            item.update(accepted=False, refusal=refusal.code, damping_numerator=-1,
                        policy_hash="", extension_identity="")
        cases.append(item)
    return {"schema": "lcb-inertial-parameter-vectors-v1", "owner_family": 4, "block_version": 2,
            "field": "damping_numerator", "minimum": 0, "maximum": 16,
            "denominator": 16, "default": 1, "state_contract": 1, "identity_version": 1,
            "default_identity": identity(), "cases": cases}


def header(data):
    rows = []
    for case in data["cases"]:
        words = ", ".join(str(w) for w in case["words"])
        rows.append('    {' + json.dumps(case["name"]) + ', {' + words + '}, ' +
                    str(case["accepted"]).lower() + ', ' + json.dumps(case["refusal"]) + ', ' +
                    str(case["damping_numerator"]) + ', ' + json.dumps(case["policy_hash"]) + ', ' +
                    json.dumps(case["extension_identity"]) + '},')
    return '''// Generated by tools/lcb/inertial_parameter_contract.py; do not edit.
#pragma once
#include <array>
#include <cstdint>
#include <vector>
namespace inertial_parameter_vectors {
struct Case {
    const char* name;
    std::vector<std::int32_t> words;
    bool accepted;
    const char* refusal;
    std::int32_t damping_numerator;
    const char* policy_hash;
    const char* extension_identity;
};
inline const std::array<Case, ''' + str(len(rows)) + '''> kCases{{
''' + "\n".join(rows) + '''
}};
} // namespace inertial_parameter_vectors
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = vectors()
    native_json = json.dumps(data, indent=2) + "\n"
    native = build()
    assignments = [(m, 4 if m == 24 else f, v) for m, f, v in pc.default_assignments(native)]
    damping = []
    for numerator in range(17):
        request = pc.encode(pc.policy_for(native, assignments, [(4, 2, [numerator])]))
        applied = pc.decode(request, native)
        damping.append({"damping_numerator": numerator, "words": request,
                        "policy_hash": pc.policy_hash(applied), "extension_identity": identity(numerator)})
    adapter = {"schema": "lcb-inertial-adapter-vectors-v1",
               "generator": "tools/lcb/inertial_parameter_contract.py identity/build and policy_contract.py encode/decode/policy_hash; no native executable",
               "canonical_native_vectors_sha256": hashlib.sha256(native_json.encode()).hexdigest(),
               "native_cases": data["cases"], "damping_cases": damping}
    expected = {JSON_PATH: native_json, HEADER_PATH: header(data),
                ADAPTER_PATH: json.dumps(adapter, indent=2) + "\n"}
    for path, text in expected.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {path.relative_to(ROOT)}")
                return 1
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    print("IN native damping-v2 vectors match" if args.check else "wrote IN native damping-v2 vectors")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
